SPECIALTIES_BY_TRACK = {
    "uni": UNIVERSITY_SPECIALTIES_BY_DEPARTMENT,
    "college": COLLEGE_SPECIALTIES_BY_DEPARTMENT,
}


def get_specialties_by_department(lang: str, track: str = "uni") -> dict[str, list[str]]:
    track_map = SPECIALTIES_BY_TRACK.get(track, UNIVERSITY_SPECIALTIES_BY_DEPARTMENT)
    return track_map.get(lang, track_map.get("ru", {}))


# Backward compatibility for old imports.
SPECIALTIES_BY_DEPARTMENT = UNIVERSITY_SPECIALTIES_BY_DEPARTMENT


def get_all_specialties(lang: str = "ru", track: str = "uni") -> list[str]:
    departments = get_specialties_by_department(lang, track)
    return [spec for specs in departments.values() for spec in specs]


